/* RegressionBanner — warning shown when the latest finished run dropped a metric by >= 1 point.
   The text is built from message templates filled from `alert`; nothing is generated by an LLM. */
"use client";

import React from "react";
import { useLocale, useTranslations } from "next-intl";
import { Icon } from "@devdigest/ui";
import type { RegressionAlert } from "@/lib/hooks/eval";
import { joinList, lowerFirst, upperFirst } from "./helpers";
import { s } from "./styles";

export function RegressionBanner({ alert }: { alert: RegressionAlert }) {
  const t = useTranslations("eval.agentDashboard.banner");
  const locale = useLocale();
  const name = (m: string) => t(`metricName.${m}`);

  const dropped = alert.dropped.map((d) => t("droppedItem", { metric: name(d.metric), points: d.points })).join(", ");
  const hintKey = alert.dropped[0]?.metric;
  const lists = (metrics: string[]) =>
    upperFirst(
      joinList(
        metrics.map((m, i) => (i === 0 ? name(m) : lowerFirst(name(m)))),
        locale,
      ),
    );
  const tail = [
    alert.rose.length ? t("rose", { metrics: lists(alert.rose), count: alert.rose.length }) : null,
    alert.held.length ? t("held", { metrics: lists(alert.held) }) : null,
  ].filter(Boolean);

  return (
    <div role="status" style={s.banner}>
      <Icon.AlertTriangle size={18} style={s.icon} aria-hidden />
      <span>
        <strong>{dropped}</strong> {t("on", { version: alert.version })}
        {hintKey ? ` — ${t(`hint.${hintKey}`)}` : ""} {tail.join(" ")}
      </span>
    </div>
  );
}
